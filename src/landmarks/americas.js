// Блок на грани: side — [sx, sz] из SIDES (наружная нормаль), (cx, cz) — центр постройки,
// u — сдвиг вдоль грани (плюс — вправо, если смотреть на грань снаружи), off — отступ до середины блока.
function fbox(a, cx, cz, [sx, sz], u, y0, off, w, h, d, c, roll = 0) {
  a.box(cx + sx * off + sz * u, y0, cz + sz * off - sx * u, w, h, d, c, Math.atan2(sx, sz), 0, roll);
}

// Круглая «шайба» радиусом r (до грани): n брусков через π/n дают 2n-угольник.
// Косые бруски чуть ниже, чтобы верх не рябил.
function disc(a, x, y0, z, r, h, c, c2 = c, n = 8) {
  const s = 2 * r * Math.tan(Math.PI / (2 * n)) + 0.02;
  for (let k = 0; k < n; k++) a.box(x, y0 + (k % 2) * 0.01, z, 2 * r, h - (k % 2) * 0.02, s, k % 2 ? c2 : c, (k * Math.PI) / n);
}

// Кольцо из n плашек по окружности радиуса r (стены, перила, стеклянные пояса) — от угла from до to.
// Угол 0 смотрит в +x, π/2 — в +z.
function ringWall(a, x, y0, z, r, h, t, c, n = 16, from = 0, to = TAU) {
  const step = (to - from) / n;
  const len = 2 * (r + t / 2) * Math.tan(step / 2) + 0.03;
  for (let k = 0; k < n; k++) {
    const ang = from + (k + 0.5) * step;
    a.box(x + Math.cos(ang) * r, y0, z + Math.sin(ang) * r, t, h, len, c, -ang);
  }
}

// Ель: ствол и четыре яруса хвои.
function pine(a, x, y0, z, s = 1, leaf = 0x2f6a3a, leaf2 = 0x3b7a45) {
  a.box(x, y0, z, 0.4 * s, 1 * s, 0.4 * s, 0x5a3a22);
  [1.9, 1.45, 1.0, 0.5].forEach((w, i) => a.box(x, y0 + (0.8 + i * 0.75) * s, z, w * s, 0.85 * s, w * s, i % 2 ? leaf2 : leaf));
}

// Машинка вдоль оси x (dir — куда едет): корпус, кабина со стёклами, крыша, колёса, фары.
function car(a, x, y0, z, c, dir = 1) {
  a.box(x, y0 + 0.18, z, 1.7, 0.5, 0.85, c);
  a.box(x - dir * 0.12, y0 + 0.68, z, 0.95, 0.4, 0.78, 0x2a3848);
  a.box(x - dir * 0.12, y0 + 1.08, z, 0.95, 0.08, 0.8, c);
  for (const e of [-0.52, 0.52]) a.box(x + e, y0, z, 0.38, 0.38, 0.9, 0x1d1d1d);
  a.box(x + dir * 0.86, y0 + 0.35, z, 0.04, 0.16, 0.6, 0xfff2b0);
}

// Фонарь: основание, столб, светящийся фонарь и шапочка.
function lamp(a, x, y0, z, h = 2.4, c = 0x2a2a2a, light = 0xffe38a) {
  a.box(x, y0, z, 0.36, 0.25, 0.36, c);
  a.box(x, y0 + 0.25, z, 0.14, h, 0.14, c);
  a.box(x, y0 + h + 0.25, z, 0.42, 0.45, 0.42, light);
  a.box(x, y0 + h + 0.7, z, 0.55, 0.12, 0.55, c);
}

// Флаг на флагштоке. Одинаковые пиксели подряд сливаются в один брусок.
// dir — куда развевается (+1/−1), alongZ — полотнище вдоль оси z.
function banner(a, x, y0, z, rows, colors, px = 0.3, pole = 3, dir = 1, alongZ = false) {
  const top = y0 + pole + rows.length * px;
  a.box(x, y0, z, 0.15, top - y0, 0.15, 0x8a8a8a);
  a.box(x, top, z, 0.26, 0.2, 0.26, GOLD);
  rows.forEach((row, r) => {
    const y = y0 + pole + (rows.length - 1 - r) * px;
    for (let c = 0; c < row.length;) {
      let e = c;
      while (e < row.length && row[e] === row[c]) e++;
      const col = colors[row[c]];
      if (col !== undefined) {
        const off = dir * (0.1 + ((c + e) / 2) * px);
        const len = (e - c) * px;
        if (alongZ) a.box(x, y, z + off, 0.06, px, len, col);
        else a.box(x + off, y, z, len, px, 0.06, col);
      }
      c = e;
    }
  });
}

