    beam(a, [x, 21.0, z], [x + sx * 0.9, 21.5, z + sz * 0.9], 0.2, GOLD);
    a.box(x + sx * 0.95, 21.3, z + sz * 0.95, 0.45, 0.45, 0.45, GOLD);
