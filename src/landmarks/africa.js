// Блок на грани: side — [sx, sz] из SIDES (наружная нормаль грани), (cx, cz) — центр постройки,
// u — сдвиг вдоль грани, off — отступ от центра до середины блока по нормали;
// w — ширина вдоль грани, d — толщина по нормали; roll — поворот в плоскости грани.
function fbox(a, cx, cz, [sx, sz], u, y0, off, w, h, d, c, roll = 0) {
  a.box(cx + sx * off + sz * u, y0, cz + sz * off - sx * u, w, h, d, c, Math.atan2(sx, sz), 0, roll);
}

// «Шестигранная» плита: три бруска через 60° — скалы, холмы и башни без острых углов.
// r — расстояние от центра до грани, углы торчат не дальше 1.16·r.
function hex(a, x, y0, z, r, h, c, c2 = c, rot = 0) {
  for (let k = 0; k < 3; k++) a.box(x, y0, z, 2 * r, h + k * 0.01, r * 1.155, k % 2 ? c2 : c, rot + (k * Math.PI) / 3);
}

// Правильный восьмигранник с апофемой r: четыре бруска через 45°.
function oct(a, x, y0, z, r, h, c, c2 = c) {
  for (let k = 0; k < 4; k++) a.box(x, y0, z, r * 2, h + k * 0.012, r * 0.83, k % 2 ? c2 : c, (k * Math.PI) / 4);
}

// Пальма: изогнутый ствол из колец, веер листьев и орехи. dir — куда наклонена.
function palm(a, x, z, h, lean = 0.2, dir = 0, y0 = 0) {
  const T = 0x8a6a44;
  const T2 = 0x74583a;
  const L = 0x4f9a3a;
  const L2 = 0x3f8a32;
  const n = Math.max(3, Math.round(h / 1.1));
  const cx = Math.cos(dir);
  const cz = Math.sin(dir);
  let px = x;
  let pz = z;
  for (let i = 0; i < n; i++) {
    const k = i / n;
    px = x + cx * lean * h * k * k;
    pz = z + cz * lean * h * k * k;
    const w = 0.6 - k * 0.15;
    a.box(px, y0 + (i * h) / n, pz, w, h / n + 0.05, w, i % 2 ? T : T2);
  }
  const top = y0 + h;
  for (let k = 0; k < 7; k++) {
    const ang = (k / 7) * TAU + x * 0.7;
    const c = Math.cos(ang);
    const s = Math.sin(ang);
    a.box(px + c * 1.1, top - 0.15, pz + s * 1.1, 2.4, 0.18, 0.65, k % 2 ? L : L2, yawAlong(c, s), 0, -0.38);
  }
  a.box(px, top - 0.1, pz, 0.9, 0.5, 0.9, L2);
  for (const [dx, dz] of [[0.35, 0], [-0.3, 0.2], [0, -0.35]]) a.box(px + dx, top - 0.55, pz + dz, 0.35, 0.35, 0.35, 0x6a4a2a);
}

// Акация-«зонтик» саванны: кривой ствол, развилка и плоская крона.
function acacia(a, x, z, h, s, y0 = 0) {
  const T = 0x6a4a2e;
  const L = 0x6f8f3a;
  const L2 = 0x5f7f32;
  const fork = [x + 0.3, y0 + h * 0.55, z];
  beam(a, [x, y0, z], fork, 0.45, T);
  beam(a, fork, [x - s * 0.28, y0 + h, z + s * 0.12], 0.3, T);
  beam(a, fork, [x + s * 0.3, y0 + h, z - s * 0.1], 0.3, T);
  a.box(x, y0 + h, z, s, 0.5, s * 0.75, L);
  a.box(x + s * 0.1, y0 + h + 0.5, z, s * 0.7, 0.35, s * 0.55, L2);
  a.box(x - s * 0.22, y0 + h - 0.25, z + 0.2, s * 0.5, 0.3, s * 0.5, L2);
}

