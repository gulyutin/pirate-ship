// Блок на грани: side — [sx, sz] (наружная нормаль грани), (cx, cz) — центр постройки,
// u — сдвиг вдоль грани, off — отступ от центра до середины блока по нормали;
// w — ширина вдоль грани, d — толщина по нормали; roll — поворот в плоскости грани.
function fbox(a, cx, cz, [sx, sz], u, y0, off, w, h, d, c, roll = 0) {
  a.box(cx + sx * off + sz * u, y0, cz + sz * off - sx * u, w, h, d, c, Math.atan2(sx, sz), 0, roll);
}

// Правильный восьмигранник с апофемой r: четыре бруска, повёрнутых через 45°.
// Высоты чуть разные, чтобы верхние грани не мерцали.
function oct(a, x, y0, z, r, h, c, c2 = c) {
  for (let k = 0; k < 4; k++) a.box(x, y0, z, r * 2, h + k * 0.012, r * 0.83, k % 2 ? c2 : c, (k * Math.PI) / 4);
}

// Грани восьмигранника: восемь нормалей [sx, sz] для fbox.
const OCT_SIDES = Array.from({ length: 8 }, (_, k) => [Math.sin((k * Math.PI) / 4), Math.cos((k * Math.PI) / 4)]);

// Круглый циферблат со стрелками «10:10» на одной грани (cy — центр циферблата, r — радиус).
function dial(a, cx, cz, side, cy, off, r, face, rim, hand) {
  const rows = 5;
  const hh = (2 * r) / rows;
  for (let i = 0; i < rows; i++) {
    const dy = -r + (i + 0.5) * hh;
    const w = 2 * Math.sqrt(Math.max(0, r * r - dy * dy)) + 0.2;
    fbox(a, cx, cz, side, 0, cy + dy - hh / 2, off, w + 0.36, hh, 0.12, rim);
    fbox(a, cx, cz, side, 0, cy + dy - hh / 2, off + 0.04, w, hh, 0.12, face);
  }
  const L1 = r * 0.78;
  const L2 = r * 0.52;
  const t = Math.PI / 3;
  fbox(a, cx, cz, side, Math.sin(t) * L1 * 0.5, cy + Math.cos(t) * L1 * 0.5 - L1 / 2, off + 0.1, 0.18, L1, 0.06, hand, -t);
  fbox(a, cx, cz, side, -Math.sin(t) * L2 * 0.5, cy + Math.cos(t) * L2 * 0.5 - L2 / 2, off + 0.1, 0.24, L2, 0.06, hand, t);
}

